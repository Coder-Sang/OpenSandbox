#!/usr/bin/env python3
"""Generate isolated Rust wire models and operation metadata from repository specs.

Requires Python >=3.9 and PyYAML (see requirements.txt). No client or Cargo tree
is generated. Dates stay wire strings, binary bodies are bytes, and constraints
are retained in schema/operation metadata rather than silently discarded.
"""
import argparse
import copy
import json
import re
import subprocess
from pathlib import Path

import yaml

class SpecLoader(yaml.SafeLoader):
    """Keep timestamps as wire strings and avoid YAML 1.1 yes/no booleans."""
    yaml_implicit_resolvers = {
        key: [(tag, regex) for tag, regex in values
              if tag not in {"tag:yaml.org,2002:timestamp", "tag:yaml.org,2002:bool"}]
        for key, values in yaml.SafeLoader.yaml_implicit_resolvers.items()
    }


SpecLoader.add_implicit_resolver("tag:yaml.org,2002:bool", re.compile(r"^(?:true|false)$"), list("tf"))
ROOT = Path(__file__).resolve().parents[4]
SPECS = {"lifecycle": "sandbox-lifecycle.yml", "execd": "execd-api.yaml", "egress": "egress-api.yaml"}
HEADER = "// SPDX-License-Identifier: Apache-2.0\n// @generated by scripts/generate_api.py. Do not edit by hand.\n"
KEYWORDS = set("as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box do final macro override priv typeof unsized virtual yield try gen".split())


def pascal(value):
    result = "".join(part[:1].upper() + part[1:] for part in re.split(r"[^a-zA-Z0-9]+", value) if part)
    return ("Value" + result if not result or result[0].isdigit() else result)


def snake(value):
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"[^a-zA-Z0-9]+", "_", value).strip("_").lower() or "value"
    if value[0].isdigit():
        value = "value_" + value
    return value + "_" if value in KEYWORDS else value


def literal(value):
    # JSON escaping is valid Rust for the ASCII identifiers/media types here.
    return json.dumps(value, ensure_ascii=False)


def raw(value):
    text = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    hashes = "#"
    while '"' + hashes in text:
        hashes += "#"
    return 'r' + hashes + '"' + text + '"' + hashes


class Generator:
    def __init__(self, spec):
        self.spec = spec
        self.definitions = {}
        self.schemas = spec.get("components", {}).get("schemas", {})
        self.names = set(self.schemas)

    def resolve(self, obj):
        if "$ref" not in obj:
            return obj
        ref = obj["$ref"]
        if not ref.startswith("#/"):
            raise ValueError("External references are not supported: " + ref)
        result = self.spec
        for part in ref[2:].split("/"):
            result = result[part.replace("~1", "/").replace("~0", "~")]
        return {**result, **{k: v for k, v in obj.items() if k != "$ref"}}

    def nullable(self, schema):
        return schema.get("nullable", False) or (isinstance(schema.get("type"), list) and "null" in schema["type"]) or any(s.get("type") == "null" for s in schema.get("oneOf", schema.get("anyOf", [])))

    def nonnull(self, schema):
        schema = copy.deepcopy(schema)
        schema.pop("nullable", None)
        if isinstance(schema.get("type"), list):
            types = [t for t in schema["type"] if t != "null"]
            if len(types) != 1:
                raise ValueError("Unsupported multi-type schema: " + str(schema))
            schema["type"] = types[0]
        for key in ("oneOf", "anyOf"):
            if key in schema:
                schema[key] = [s for s in schema[key] if s.get("type") != "null"]
                if len(schema[key]) == 1:
                    child = schema.pop(key)[0]
                    schema = {**schema, **child}
        return schema

    def type_for(self, schema, name):
        if self.nullable(schema):
            return "Option<" + self.type_for(self.nonnull(schema), name) + ">"
        if "$ref" in schema:
            ref = schema["$ref"]
            if not ref.startswith("#/components/schemas/"):
                raise ValueError("Non-model schema reference: " + ref)
            return ref.rsplit("/", 1)[1]
        if "enum" in schema or "const" in schema or "oneOf" in schema or "anyOf" in schema or schema.get("properties") or "allOf" in schema:
            self.define(name, schema)
            return name
        typ = schema.get("type", "object")
        if typ == "array":
            return "Vec<" + self.type_for(schema.get("items", {}), name + "Item") + ">"
        if typ == "object":
            additional = schema.get("additionalProperties", True)
            value = self.type_for(additional, name + "Value") if isinstance(additional, dict) else "serde_json::Value"
            return "std::collections::BTreeMap<String, " + value + ">"
        if typ == "string":
            return "Vec<u8>" if schema.get("format") == "binary" else "String"
        if typ == "integer":
            return "i32" if schema.get("format") == "int32" else "i64"
        if typ == "number":
            return "f32" if schema.get("format") == "float" else "f64"
        if typ == "boolean":
            return "bool"
        if typ == "null":
            return "()"
        raise ValueError("Unsupported type: " + str(schema))

    def define(self, name, schema):
        if name in self.definitions:
            if self.definitions[name][0] != schema:
                raise ValueError("Generated model name collision: " + name)
            return
        self.definitions[name] = (schema, "")
        if "enum" in schema or "const" in schema:
            values = schema.get("enum", [schema.get("const")])
            if not values or any(not isinstance(v, str) for v in values):
                raise ValueError("Only string enums supported: " + name)
            variants = [pascal(v) for v in values]
            if len(set(variants)) != len(variants):
                raise ValueError("Enum variant collision: " + name)
            lines = ["#[derive(Clone, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]", f"pub enum {name} {{"]
            for i, (value, variant) in enumerate(zip(values, variants)):
                if i == 0:
                    lines.append("    #[default]")
                lines.extend([f"    #[serde(rename = {literal(value)})]", f"    {variant},"])
            if len(values) > 1 and "const" not in schema:
                lines.append("    Unknown(String),")
            lines.append("}")
            if len(values) > 1 and "const" not in schema:
                lines[0] = "#[derive(Clone, Debug, Default, PartialEq, Eq)]"
                lines = [line for line in lines if not line.strip().startswith("#[serde(rename")]
                lines += [f"impl serde::Serialize for {name} {{", "    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {", "        serializer.serialize_str(match self {"]
                lines += [f"            Self::{variant} => {literal(value)}," for value, variant in zip(values, variants)]
                lines += ["            Self::Unknown(value) => value.as_str(),", "        })", "    }", "}", f"impl<'de> serde::Deserialize<'de> for {name} {{", "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {", "        let value = <String as serde::Deserialize>::deserialize(deserializer)?;", "        Ok(match value.as_str() {"]
                lines += [f"            {literal(value)} => Self::{variant}," for value, variant in zip(values, variants)]
                lines += ["            _ => Self::Unknown(value),", "        })", "    }", "}"]
        elif "oneOf" in schema or "anyOf" in schema:
            key = "oneOf" if "oneOf" in schema else "anyOf"
            variants = []
            for i, child in enumerate(schema[key]):
                typ = self.type_for(child, name + f"Variant{i + 1}")
                variant = child.get("$ref", "").rsplit("/", 1)[-1] or f"Variant{i + 1}"
                variants.append((variant, typ))
            lines = ["#[derive(Clone, Debug, PartialEq, serde::Serialize)]", "#[serde(untagged)]", f"pub enum {name} {{"]
            lines += [f"    {v}({t})," for v, t in variants]
            lines += ["}", f"impl Default for {name} {{", f"    fn default() -> Self {{ Self::{variants[0][0]}(Default::default()) }}", "}", f"impl<'de> serde::Deserialize<'de> for {name} {{", "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {", "        let value = <serde_json::Value as serde::Deserialize>::deserialize(deserializer)?;", "        let mut matched = None;", "        let mut count = 0;"]
            for variant, typ in variants:
                lines += [f"        if let Ok(model) = serde_json::from_value::<{typ}>(value.clone()) {{", f"            matched = Some(Self::{variant}(model));", "            count += 1;", "        }"]
            check = "count == 1" if key == "oneOf" else "count >= 1"
            lines += [f"        if {check} {{ Ok(matched.unwrap()) }} else {{", f"            Err(serde::de::Error::custom({literal(name + ': value does not satisfy ' + key)}))", "        }", "    }", "}"]
        else:
            props = dict(schema.get("properties", {}))
            required = set(schema.get("required", []))
            for child in schema.get("allOf", []):
                child = self.resolve(child)
                # Constraint-only oneOf (e.g. command xor argv) is retained in SCHEMAS.
                if set(child) <= {"oneOf", "description"} and all(set(x) <= {"required"} for x in child.get("oneOf", [])):
                    continue
                if "oneOf" in child or "anyOf" in child:
                    raise ValueError("Unsupported composed object: " + name)
                props.update(child.get("properties", {}))
                required.update(child.get("required", []))
            if not props:
                typ = self.type_for({k: v for k, v in schema.items() if k != "allOf"}, name + "Value")
                lines = [f"pub type {name} = {typ};"]
            else:
                lines = ["#[derive(Clone, Debug, Default, PartialEq, serde::Serialize, serde::Deserialize)]", f"pub struct {name} {{"]
                fields = set()
                for wire, child in props.items():
                    field = snake(wire)
                    if field in fields:
                        raise ValueError("Field collision: " + name + "." + field)
                    fields.add(field)
                    nullable = self.nullable(child)
                    typ = self.type_for(child, name + pascal(wire))
                    attrs = ["rename = " + literal(wire)]
                    if wire not in required:
                        typ = "Option<" + typ + ">"
                        attrs += ["default", 'skip_serializing_if = "Option::is_none"']
                        if nullable:
                            attrs += ['deserialize_with = "super::deserialize_present_nullable"']
                    lines += ["    #[serde(" + ", ".join(attrs) + ")]", f"    pub {field}: {typ},"]
                additional = schema.get("additionalProperties")
                if additional is not False:
                    typ = self.type_for(additional, name + "AdditionalProperty") if isinstance(additional, dict) else "serde_json::Value"
                    field = "additional_properties"
                    if field in fields:
                        raise ValueError("Flattened field collision: " + name)
                    lines += ["    #[serde(flatten)]", f"    pub {field}: std::collections::BTreeMap<String, {typ}>,"]
                lines += ["}"]
                groups = [child["oneOf"] for child in schema.get("allOf", []) if "oneOf" in child]
                if groups:
                    helper = name + "Wire"
                    helper_lines = [line.replace(f"pub struct {name}", f"struct {helper}").replace("pub ", "") for line in lines]
                    helper_lines[0] = "#[derive(serde::Deserialize)]"
                    lines[0] = "#[derive(Clone, Debug, Default, PartialEq, serde::Serialize)]"
                    lines += helper_lines
                    lines += [f"impl<'de> serde::Deserialize<'de> for {name} {{", "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {", f"        let wire = <{helper} as serde::Deserialize>::deserialize(deserializer)?;"]
                    for group in groups:
                        checks = []
                        for branch in group:
                            checks.append("(" + " && ".join("wire." + snake(field) + ".is_some()" if field not in required else "true" for field in branch.get("required", [])) + ") as usize")
                        lines += ["        if " + " + ".join(checks) + " != 1 {", f"            return Err(serde::de::Error::custom({literal(name + ': exactly one required branch must match')}));", "        }"]
                    names = [snake(field) for field in props]
                    if additional is not False:
                        names.append("additional_properties")
                    lines += ["        Ok(Self { " + ", ".join(field + ": wire." + field for field in names) + " })", "    }", "}"]
        # Wire objects can carry credentials, commands, environment and arbitrary
        # extension maps. Redact the entire model rather than guessing secret keys.
        if any(line.startswith(f"pub struct {name} ") or line.startswith(f"pub enum {name} ") for line in lines):
            lines = [line.replace("Clone, Debug,", "Clone,") for line in lines]
            lines += [f"impl std::fmt::Debug for {name} {{", "    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {", f"        formatter.write_str({literal(name + '(<redacted>)')})", "    }", "}"]
        self.definitions[name] = (schema, "\n".join(lines))

    def media(self, content, name):
        result = []
        for i, (media_type, item) in enumerate(content.items()):
            schema = item.get("schema", {})
            typ = self.type_for(schema, name + ("" if len(content) == 1 else str(i + 1))) if schema else "()"
            result.append("super::MediaType { content_type: " + literal(media_type) + ", rust_type: " + literal(typ) + ", schema: " + raw(schema) + ", encoding: " + raw(item.get("encoding", {})) + " }")
        return "&[" + ", ".join(result) + "]"

    def generate(self):
        for name, schema in self.schemas.items():
            self.define(name, schema)
        ops = []
        for path, item in self.spec.get("paths", {}).items():
            item = self.resolve(item)
            for method, op in item.items():
                if method not in {"get", "put", "post", "delete", "patch", "head", "options", "trace"}:
                    continue
                operation_id = op.get("operationId", snake(method + "_" + path))
                name = pascal(operation_id)
                params = {}
                for p in item.get("parameters", []) + op.get("parameters", []):
                    p = self.resolve(p)
                    params[(p["in"], p["name"])] = p
                parameters = []
                for p in params.values():
                    typ = self.type_for(p.get("schema", {}), name + pascal(p["name"]) + "Parameter")
                    parameters.append("super::Parameter { name: " + literal(p["name"]) + ", location: " + literal(p["in"]) + ", required: " + str(p.get("required", False)).lower() + ", rust_type: " + literal(typ) + ", schema: " + raw(p.get("schema", {})) + ", style: " + literal(p.get("style", "form" if p["in"] in {"query", "cookie"} else "simple")) + ", explode: " + str(p.get("explode", p.get("style", "form" if p["in"] in {"query", "cookie"} else "simple") == "form")).lower() + " }")
                body = self.resolve(op.get("requestBody", {}))
                request = self.media(body.get("content", {}), name + "RequestBody")
                responses = []
                for status, response in op.get("responses", {}).items():
                    response = self.resolve(response)
                    media = self.media(response.get("content", {}), name + "Response" + pascal(str(status)))
                    responses.append("super::Response { status: " + literal(str(status)) + ", content: " + media + ", headers: " + raw(response.get("headers", {})) + " }")
                ops.append("super::Operation { id: " + literal(operation_id) + ", method: " + literal(method.upper()) + ", path: " + literal(path) + ", parameters: &[" + ", ".join(parameters) + "], request_required: " + str(body.get("required", False)).lower() + ", request: " + request + ", responses: &[" + ", ".join(responses) + "], security: " + raw(op.get("security", self.spec.get("security", []))) + " }")
        definitions = "\n\n".join(self.definitions[n][1] for n in sorted(self.definitions))
        schemas = "\n".join("    (" + literal(n) + ", " + raw(s) + ")," for n, s in self.schemas.items())
        return HEADER + definitions + "\n\npub const SCHEMAS: &[(&str, &str)] = &[\n" + schemas + "\n];\n\npub const OPERATIONS: &[super::Operation] = &[\n" + ",\n".join(ops) + "\n];\n\n/// Resolve a generated operation for the SDK's shared transport.\npub fn operation(id: &str) -> Option<&'static super::Operation> {\n    OPERATIONS.iter().find(|operation| operation.id == id)\n}\n"


MOD = HEADER + '''//! Isolated wire models and API operation metadata generated from OpenAPI 3.1.
//! This layer has no HTTP client. Binary/multipart metadata is not JSON transport.
pub mod lifecycle;
pub mod execd;
pub mod egress;

#[derive(Clone, Copy, Debug)]
pub struct Parameter {
    pub name: &'static str,
    pub location: &'static str,
    pub required: bool,
    pub rust_type: &'static str,
    pub schema: &'static str,
    pub style: &'static str,
    pub explode: bool,
}
#[derive(Clone, Copy, Debug)]
pub struct MediaType {
    pub content_type: &'static str,
    pub rust_type: &'static str,
    pub schema: &'static str,
    pub encoding: &'static str,
}
#[derive(Clone, Copy, Debug)]
pub struct Response {
    pub status: &'static str,
    pub content: &'static [MediaType],
    pub headers: &'static str,
}
#[derive(Clone, Copy, Debug)]
pub struct Operation {
    pub id: &'static str,
    pub method: &'static str,
    pub path: &'static str,
    pub parameters: &'static [Parameter],
    pub request_required: bool,
    pub request: &'static [MediaType],
    pub responses: &'static [Response],
    pub security: &'static str,
}
// Outer None = absent, Some(None) = explicit JSON null, Some(Some(T)) = value.
fn deserialize_present_nullable<'de, D, T>(deserializer: D) -> Result<Option<Option<T>>, D::Error>
where D: serde::Deserializer<'de>, T: serde::Deserialize<'de> {
    <Option<T> as serde::Deserialize>::deserialize(deserializer).map(Some)
}
'''


def outputs(spec_dir):
    result = {"mod.rs": MOD + "\n" + Path(__file__).with_name("wire_tests.rs").read_text()}
    for module, filename in SPECS.items():
        spec = yaml.load((spec_dir / filename).read_text(), Loader=SpecLoader)
        if spec.get("openapi") != "3.1.0":
            raise ValueError("Expected OpenAPI 3.1.0: " + filename)
        result[module + ".rs"] = Generator(spec).generate()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec-dir", type=Path, default=ROOT / "specs")
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "src/api")
    parser.add_argument("--check", action="store_true", help="Fail if checked-in output differs")
    args = parser.parse_args()
    generated = outputs(args.spec_dir)
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    # rustfmt is part of the pinned SDK Rust toolchain, not a template post-patch.
    stale = []
    for filename, content in generated.items():
        formatted = subprocess.run(["rustfmt", "--edition", "2021", "--config", "skip_children=true"], input=content, text=True, capture_output=True, check=True).stdout
        target = args.output_dir / filename
        if args.check:
            if not target.exists() or target.read_text() != formatted:
                stale.append(filename)
        else:
            target.write_text(formatted)
    if stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
